import { calculateRetentions, DEFAULT_RETENTION_RULES } from "./retention";
import type { HistoryEntry, Invoice, MoneyBreakdown } from "./types";

function demoInvoice(
  invoice: Omit<Invoice, "retentionLines" | "retentionTotal" | "updatedAt">,
): Invoice {
  const retention = calculateRetentions(invoice.amounts, DEFAULT_RETENTION_RULES);
  return {
    ...invoice,
    updatedAt: invoice.createdAt,
    retentionLines: retention.lines,
    retentionTotal: retention.total,
  };
}

